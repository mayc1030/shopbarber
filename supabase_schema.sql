-- =========================================================================
-- 1. CREACIÓN DE TABLAS
-- =========================================================================

-- Tabla de perfiles de usuario (conecta con Supabase Auth)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade not null primary key,
  is_admin boolean default false not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tabla de barberos
create table if not exists public.barbers (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null unique,
  login_email text,
  name text not null,
  photo_url text,
  bio text,
  specialties text[],
  active boolean default true not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tabla de servicios
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  duration_minutes integer not null,
  price numeric not null,
  description text,
  active boolean default true not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tabla de citas/reservas
create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  client_name text not null,
  client_phone text not null,
  client_email text,
  client_token text,
  price_at_booking numeric,
  barber_id bigint references public.barbers(id) on delete cascade not null,
  service_id bigint references public.services(id) on delete cascade not null,
  appointment_date date not null,
  appointment_time time without time zone not null,
  status text default 'pending'::text check (status in ('pending', 'scheduled', 'completed', 'cancelled')) not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Índice para consultar citas propias del cliente mediante token local
create index if not exists appointments_client_token_idx
  on public.appointments (client_token)
  where client_token is not null;

-- Evita doble reserva simultánea para el mismo barbero, fecha y hora (salvo citas canceladas)
create unique index if not exists appointments_no_double_booking_idx
  on public.appointments (barber_id, appointment_date, appointment_time)
  where status <> 'cancelled';

-- Tabla de configuraciones dinámicas del sitio (textos, galería, horarios, redes)
create table if not exists public.settings (
  id text primary key,
  value text not null default '',
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- =========================================================================
-- 2. HABILITAR SEGURIDAD RLS (Row Level Security)
-- =========================================================================

alter table public.profiles enable row level security;
alter table public.barbers enable row level security;
alter table public.services enable row level security;
alter table public.appointments enable row level security;
alter table public.settings enable row level security;

-- =========================================================================
-- 3. FUNCIONES AUXILIARES Y POLÍTICAS DE ACCESO (RLS Policies)
-- =========================================================================

-- Función segura (SECURITY DEFINER) para comprobar si es administrador sin causar bucles infinitos
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and is_admin = true
  );
$$;

-- Función pública segura para consultar únicamente horarios ocupados sin exponer datos de clientes
create or replace function public.get_busy_slots(p_barber_id bigint, p_date date)
returns table (
  appointment_time time without time zone,
  duration_minutes integer
)
language sql
security definer
set search_path = public
as $$
  select
    a.appointment_time,
    coalesce(s.duration_minutes, 30) as duration_minutes
  from public.appointments a
  left join public.services s on s.id = a.service_id
  where a.barber_id = p_barber_id
    and a.appointment_date = p_date
    and a.status <> 'cancelled';
$$;

grant execute on function public.get_busy_slots(bigint, date) to anon, authenticated;

-- Función pública segura para consultar historial propio por tokens guardados en localStorage
create or replace function public.get_my_appointments(p_tokens text[])
returns table (
  id bigint,
  appointment_date date,
  appointment_time time without time zone,
  status text,
  service_name text,
  duration_minutes integer,
  price numeric,
  barber_name text,
  created_at timestamp with time zone
)
language sql
security definer
set search_path = public
as $$
  select
    a.id,
    a.appointment_date,
    a.appointment_time,
    a.status,
    coalesce(s.name, 'Servicio') as service_name,
    coalesce(s.duration_minutes, 30) as duration_minutes,
    coalesce(a.price_at_booking, s.price, 0) as price,
    coalesce(b.name, 'Sin Asignar') as barber_name,
    a.created_at
  from public.appointments a
  left join public.services s on s.id = a.service_id
  left join public.barbers b on b.id = a.barber_id
  where a.client_token = any(p_tokens)
  order by a.appointment_date desc, a.appointment_time desc;
$$;

grant execute on function public.get_my_appointments(text[]) to anon, authenticated;

-- Políticas para PROFILES
create policy "Usuarios leen su propio perfil"
  on public.profiles for select
  using (auth.uid() = id);

create policy "Admin maneja todos los perfiles"
  on public.profiles for all
  using (public.is_admin());

-- Políticas para BARBERS
create policy "Público puede ver barberos activos"
  on public.barbers for select
  using (active = true);

create policy "Barberos pueden actualizar su propio perfil"
  on public.barbers for update
  using (auth.uid() = user_id);

create policy "Admin controla tabla de barberos"
  on public.barbers for all
  using (public.is_admin());

-- Políticas para SERVICES
create policy "Público puede ver servicios activos"
  on public.services for select
  using (active = true);

create policy "Admin controla tabla de servicios"
  on public.services for all
  using (public.is_admin());

-- Políticas para APPOINTMENTS (sin SELECT público directo para proteger privacidad)
create policy "Público puede crear reservas"
  on public.appointments for insert
  with check (status = 'pending');

create policy "Admin y Barberos asignados leen citas"
  on public.appointments for select
  using (
    public.is_admin()
    or barber_id in (select id from public.barbers where user_id = auth.uid())
  );

create policy "Admin y Barberos asignados actualizan citas"
  on public.appointments for update
  using (
    public.is_admin()
    or barber_id in (select id from public.barbers where user_id = auth.uid())
  );

-- Políticas para SETTINGS
create policy "Público puede leer configuraciones"
  on public.settings for select
  using (true);

create policy "Admin controla configuraciones"
  on public.settings for all
  using (public.is_admin());

-- =========================================================================
-- 4. STORAGE BUCKET 'logos' (Logos, Fotos de Barberos y Galería)
-- =========================================================================

insert into storage.buckets (id, name, public)
values ('logos', 'logos', true)
on conflict (id) do nothing;

create policy "Lectura pública de imágenes en logos"
  on storage.objects for select
  using (bucket_id = 'logos');

create policy "Staff autenticado puede subir imágenes a logos"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'logos'
    and (
      public.is_admin()
      or exists (select 1 from public.barbers where user_id = auth.uid())
    )
  );

create policy "Admin puede eliminar imágenes de logos"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'logos' and public.is_admin());

-- =========================================================================
-- 5. DISPARADOR (TRIGGER) PARA CREAR PERFILES AUTOMÁTICAMENTE
-- =========================================================================

create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, is_admin)
  values (new.id, false)
  on conflict (id) do nothing;
  return new;
end;
$$ language plpgsql security definer;

create or replace trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

